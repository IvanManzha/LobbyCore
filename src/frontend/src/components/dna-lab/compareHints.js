const NEUTRAL_HINTS = [
  "Оба близко — решает стабильность и контекст матчей.",
  "Разница в пределах погрешности.",
  "Контекст матчей может объяснить небольшую разницу.",
];

const LOW_SAMPLE_HINT = "Мало матчей в срезе.";

/**
 * Pick one hint for the given gene and diff.
 * @param {string} geneKey
 * @param {number} diff - valueMe - valueOpp (positive = me higher, negative = opponent higher)
 * @param {boolean} lowSample
 * @returns {string}
 */
export function pickHint(geneKey, diff, lowSample) {
  if (lowSample) return LOW_SAMPLE_HINT;

  const hints = HINTS[geneKey];
  if (!hints || hints.length === 0) return NEUTRAL_HINTS[0];

  if (diff <= -8) {
    return hints[Math.floor(Math.random() * 9)] ?? hints[0];
  }
  if (diff >= 8) {
    const hintsMe = HINTS_ME[geneKey];
    if (hintsMe && hintsMe.length >= 9) {
      return hintsMe[Math.floor(Math.random() * 9)] ?? hintsMe[0];
    }
    return hints[9] ?? NEUTRAL_HINTS[0];
  }

  return NEUTRAL_HINTS[Math.floor(Math.random() * NEUTRAL_HINTS.length)];
}

export { HINTS };
